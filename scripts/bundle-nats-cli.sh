set -euo pipefail

cd "$(dirname "$0")/.."

version=v0.3.0
build_dir=$(mktemp -d)
trap 'rm -rf "$build_dir"' EXIT

# Download into the module cache and build the upstream command using its own go.mod.
module_dir=$(go mod download -json "github.com/nats-io/natscli@$version" |
  python3 -c 'import json, sys; print(json.load(sys.stdin)["Dir"])')
target_dir="$PWD/internal/natsshell/bundle"
mkdir -p "$target_dir"

for target in "$@"; do
  os=${target%/*}
  arch=${target#*/}
  case "$target" in
    linux/amd64|linux/arm64|darwin/amd64|darwin/arm64) ;;
    *) echo "Unsupported target: $target" >&2; exit 1 ;;
  esac
  name="nats_${os}_${arch}"
  (
    cd "$module_dir"
    CGO_ENABLED=0 GOOS="$os" GOARCH="$arch" go build -mod=readonly -buildvcs=false -trimpath \
      -ldflags="-s -w -X main.version=$version" -o "$build_dir/$name" ./nats
  )
  mv "$build_dir/$name" "$target_dir/$name"
  cat > "internal/natsshell/bundle_${os}_${arch}.go" <<GO
// Code generated by scripts/bundle-nats-cli.sh. DO NOT EDIT.

package natsshell

import _ "embed"

//go:embed bundle/$name
var platformNATS []byte

func init() {
	bundledNATS = platformNATS
}
GO
done
